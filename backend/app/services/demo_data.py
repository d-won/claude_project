def build_demo_statements(ticker: str, years: int = 10) -> list[FinancialStatement]:
    """Build FinancialStatement objects from demo data."""
    raw = DEMO_DATA.get(ticker, [])
    if not raw:
        return []

    company = DEMO_COMPANIES.get(ticker)
    currency = company.currency if company else "USD"
    scale = 1e6  # data in millions
    if ticker in ("005930.KS", "000660.KS"):
        scale = 1e9  # data in billions KRW
    elif ticker == "7203.T":
        scale = 1e9  # data in billions JPY

    statements = []
    for row in raw[-years:]:
        (yr, rev, cogs, gross, op, ni, ta, tl, te, debt, cash,
         ocf, capex, ebitda, depr, interest, tax, divs, shares, eps) = row
        statements.append(FinancialStatement(
            year=yr,
            revenue=rev * scale,
            cost_of_revenue=cogs * scale,
            gross_profit=gross * scale,
            operating_income=op * scale,
            net_income=ni * scale,
            total_assets=ta * scale,
            total_liabilities=tl * scale,
            total_equity=te * scale,
            total_debt=debt * scale,
            cash_and_equivalents=cash * scale,
            operating_cash_flow=ocf * scale,
            capital_expenditure=capex * scale,
            free_cash_flow=(ocf + capex) * scale,
            ebitda=ebitda * scale,
            depreciation=depr * scale,
            interest_expense=interest * scale,
            tax_expense=tax * scale,
            dividends_paid=divs * scale,
            shares_outstanding=shares * (1e3 if ticker in ("005930.KS", "000660.KS", "7203.T") else 1e6),
            eps=eps,
            currency=currency,
        ))
    return statements
